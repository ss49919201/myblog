import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { generateKeyPair, exportJWK, exportPKCS8 } from 'jose'

const dir = path.dirname(fileURLToPath(import.meta.url))
const testDir = path.join(dir, '..', 'test')
const fixturesDir = path.join(testDir, 'fixtures')

const { publicKey, privateKey } = await generateKeyPair('RS256', {
  extractable: true,
})
const jwk = await exportJWK(publicKey)
jwk.alg = 'RS256'
jwk.use = 'sig'
jwk.kid = 'test-key'

const jwks = { keys: [jwk] }
const privatePem = await exportPKCS8(privateKey)
const jwksJson = JSON.stringify(jwks)

writeFileSync(
  path.join(fixturesDir, 'jwks.json'),
  `${JSON.stringify(jwks, null, 2)}\n`,
)
writeFileSync(path.join(fixturesDir, 'test-private.pem'), privatePem)

writeFileSync(
  path.join(testDir, 'test-private-key.ts'),
  `/** Test-only RSA key; regenerated by \`node scripts/generate-test-jwks.mjs\`. */\nexport const TEST_PRIVATE_KEY_PEM = \`${privatePem}\`\n`,
)

writeFileSync(
  path.join(testDir, 'test-jwks.ts'),
  `/** Test JWKS; regenerated by \`node scripts/generate-test-jwks.mjs\`. */\nexport const TEST_JWKS_JSON =\n  '${jwksJson.replace(/'/g, "\\'")}'\n`,
)

const vitestWranglerPath = path.join(dir, '..', 'wrangler.vitest.jsonc')
const vitestConfig = {
  $schema: '../../node_modules/wrangler/config-schema.json',
  name: 'myblog-admin',
  main: 'src/index.ts',
  compatibility_date: '2026-10-08',
  d1_databases: [
    {
      binding: 'DB',
      database_name: 'myblog-web',
      database_id: 'local-test-database',
    },
  ],
  vars: {
    CF_ACCESS_TEAM_DOMAIN: 'test.cloudflareaccess.com',
    CF_ACCESS_AUD: 'test-access-audience',
    PUBLIC_WEB_ORIGIN: 'http://example.com',
    ACCESS_JWKS_JSON: jwksJson,
  },
}
writeFileSync(vitestWranglerPath, `${JSON.stringify(vitestConfig, null, 2)}\n`)

console.log('wrote test JWKS fixtures')
